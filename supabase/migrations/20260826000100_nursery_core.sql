create or replace function public.cancel_nursery_sale(
  target_sale_id uuid,
  target_reason text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  target_sale public.nursery_sales%rowtype;
  active_paid numeric;
begin
  select * into target_sale from public.nursery_sales
  where id = target_sale_id for update;
  if target_sale.id is null then raise exception 'nursery_sale_not_found'; end if;
  if not public.can_manage_company(target_sale.company_id) then raise exception 'not_allowed'; end if;
  if nullif(trim(target_reason), '') is null then raise exception 'nursery_cancellation_reason_required'; end if;
  select coalesce(sum(allocation.amount), 0) into active_paid
  from public.nursery_receipt_allocations allocation
  join public.nursery_receipts receipt on receipt.id = allocation.receipt_id
  where allocation.sale_id = target_sale.id and receipt.voided_at is null;
  if active_paid > 0 then raise exception 'nursery_sale_has_active_receipts'; end if;
  if target_sale.cancelled_at is null then
    update public.nursery_sales
    set cancelled_at = now(), cancellation_reason = trim(target_reason), updated_at = now()
    where id = target_sale.id returning * into target_sale;
  end if;
  return jsonb_build_object('saleId', target_sale.id, 'cancelledAt', target_sale.cancelled_at);
end;
