-- Nursery commercial core.
-- Keeps nursery cash control separate from greenhouse harvest sales while reusing
-- Mira's company, membership, audit, and RLS foundations.

create table if not exists public.nurseries (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null default 'Vivero',
  code text not null default 'vivero',
  is_active boolean not null default true,
  created_by uuid references auth.users(id) default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, company_id),
  unique (company_id, code),
  constraint nurseries_name_required check (nullif(trim(name), '') is not null),
  constraint nurseries_code_required check (nullif(trim(code), '') is not null)
);

create table if not exists public.nursery_customers (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  display_name text not null,
  phone text,
  notes text,
  is_active boolean not null default true,
